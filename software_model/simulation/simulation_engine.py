
"""
Simulation Engine for the two-chiplet capstone model.

Purpose:
    Simulate packets traveling between Chiplet 0 and Chiplet 1
    over one electrical or optical interconnect.

Inputs:
    graph   - Contains the two chiplets and link properties.
    traffic - Contains the packets to be transmitted.
    routing - Contains the path each packet should follow.

Outputs:
    A list of PacketResult objects containing:
        - Packet generation time
        - Transmission start time
        - Transmission finish time
        - Arrival time
        - Queuing delay
        - Serialization time
        - Total packet latency
        - Communication energy

Assumptions:
    1. Exactly two chiplets: 0 and 1
    2. Exactly one bidirectional interconnect
    3. The link is full-duplex: both directions can transmit independently
    4. Packets are transmitted in generation-time order
    5. No packet loss, BER injection, or retransmissions yet
    6. Link bandwidth is in GB/s (decimal gigabytes/second)
    7. Link latency is in nanoseconds
    8. Packet size is in bytes
    9. Packet generation time is in clock cycles
"""

from dataclasses import dataclass
from math import isfinite

# Import the classes already defined in other project files
# Done instead of creating separate graph, traffic, or routing structures.
from ..simulation_setup.classes import (
    Graph,
    RoutingTable,
    TrafficTrace,
)


# 1. PACKET RESULT
@dataclass(frozen=True)
class PacketResult:
    """
    Stores the simulation results for ONE packet.

    This class is the output data structure of the
    Simulation Engine.

    The Performance Analyzer will use these values to
    calculate average latency, maximum latency, throughput,
    and potentially total communication energy.
    """

    # Chiplet IDs
    source: int
    destination: int

    # Other variables/properties of packet
    packet_size_bytes: int # Original packet size in bytes
    generation_ns: float # Time when the packet was generated, in nanoseconds
    start_ns: float # Time when the packet begins transmission
    finish_tx_ns: float # Time when all packet bytes have been serialized
    arrival_ns: float # Time when the packet arrives at the receiving chiplet
    queue_delay_ns: float # Time spent waiting for the link to become available
    serialization_ns: float # Time required to serialize the packet onto the link
    latency_ns: float # Total time from generation to arrival

    # Estimated energy used to transmit the packet, in pJ.
    # None means energy-per-bit data was not provided.
    energy_pj: float | None

# 2. MAIN SIMULATION FUNCTION
def simulate(
    graph: Graph,
    traffic: TrafficTrace,
    routing: RoutingTable,
    clock_period_ns: float = 1.0,
) -> list[PacketResult]:
    """
    Simulate packet transmission between two chiplets.

    Parameters
    ----------
    graph:
        Contains Chiplet 0, Chiplet 1, and their interconnect.

    traffic:
        Contains PacketEvent objects generated by the
        Traffic Generator.

    routing:
        Contains the routes selected by the Router.
        Valid routes are [0, 1] and [1, 0].

    clock_period_ns:
        Duration of one simulation clock cycle in ns.
        (We will do default = 1 ns/cycle)

    Returns:
    list[PacketResult]:
        One result for each simulated packet.
    """

    # STEP 1: VALIDATE THE CLOCK PERIOD

    # A clock period must be a positive, finite number.
    # A zero, negative, infinite, or NaN value is invalid.

    if not isfinite(clock_period_ns) or clock_period_ns <= 0:
        raise ValueError(
            "clock_period_ns must be finite and positive"
        )

    # STEP 2: VALIDATE THE GRAPH

    # Extract all chiplet IDs from the graph.
    # Sort them so the order does not matter.

    chiplet_ids = sorted(
        vertex.chiplet_id for vertex in graph.vertices
    )

    # Our current capstone model only supports two chiplets.
    if chiplet_ids != [0, 1]:
        raise ValueError(
            "This simulator requires chiplets with IDs 0 and 1"
        )

    # For now, there must be exactly one interconnect.
    if len(graph.edges) != 1:
        raise ValueError(
            "Exactly one link is required"
        )

    # Get the edge connecting the chiplets.
    edge = graph.edges[0]

    # Verify that the edge connects Chiplet 0 and Chiplet 1.
    edge_ids = {
        edge.source.chiplet_id,
        edge.destination.chiplet_id,
    }

    if edge_ids != {0, 1}:
        raise ValueError(
            "Link must connect chiplets 0 and 1"
        )

    # Get the link's physical properties.
    # These may describe an electrical or optical link.
    link = edge.link

    # STEP 3: VALIDATE THE LINK PARAMETERS

    # Bandwidth must exist and must be greater than zero.
    # Units: GB/s

    if (
        link.bandwidth is None
        or not isfinite(link.bandwidth)
        or link.bandwidth <= 0
    ):
        raise ValueError(
            "Link bandwidth must be finite and positive (GB/s)"
        )

    # Total link latency must exist and cannot be negative.
    # Units: nanoseconds

    if (
        link.total_latency is None
        or not isfinite(link.total_latency)
        or link.total_latency < 0
    ):
        raise ValueError(
            "Link total_latency must be finite and "
            "nonnegative (ns)"
        )

    # Energy per bit is optional.
    # If provided, it must be nonnegative and finite.
    # Units: pJ/bit

    if link.energy_per_bit is not None:
        if (
            not isfinite(link.energy_per_bit)
            or link.energy_per_bit < 0
        ):
            raise ValueError(
                "energy_per_bit must be finite and nonnegative"
            )

    # STEP 4: INITIALIZE LINK AVAILABILITY

    # This dictionary stores the earliest time each
    # transmission direction becomes available.
    
    # (0, 1) means traffic from Chiplet 0 -> Chiplet 1.
    # (1, 0) means traffic Chiplet 1 -> Chiplet 0.
    
    # Both directions start available at time 0 ns
    # Separate entries model a full-duplex link

    next_free = {
        (0, 1): 0.0,
        (1, 0): 0.0,
    }

    # Store all completed packet calculations here.
    results = []


    # STEP 5: PROCESS PACKETS IN CHRONOLOGICAL ORDER

    # Sort packets by generation time.
    #
    # This ensures earlier packets are processed first.
    # Packets generated at the same time retain their
    # original order in the traffic trace.

    sorted_packets = sorted(
        traffic.events,
        key=lambda packet: packet.generation_time,
    )

    for packet in sorted_packets:

        # STEP 5A: VALIDATE THE PACKET
        # Packets must travel between different chiplets.
        # Only 0 -> 1 and 1 -> 0 are supported.

        if (
            packet.source not in (0, 1)
            or packet.destination not in (0, 1)
            or packet.source == packet.destination
        ):
            raise ValueError(
                "Packets must travel between chiplets 0 and 1"
            )

        # Packet generation time must be valid.
        if (
            not isfinite(packet.generation_time)
            or packet.generation_time < 0
        ):
            raise ValueError(
                "Packet generation time must be "
                "finite and nonnegative"
            )

        # Packet size must be a positive integer.
        # A boolean is not accepted as a packet size.
        if (
            type(packet.packet_size) is not int
            or packet.packet_size <= 0
        ):
            raise ValueError(
                "Packet size must be a positive integer "
                "number of bytes"
            )

        # STEP 5B: VERIFY THE ROUTE
        # Ask the RoutingTable for the path between
        # the source and destination chiplets.
        path = routing.get_route(
            packet.source,
            packet.destination,
        )

        # With only two chiplets and one direct link,
        # the route must be [0, 1] or [1, 0]
        expected_path = [
            packet.source,
            packet.destination,
        ]

        if path != expected_path:
            raise ValueError(
                f"Missing or invalid direct route: "
                f"{packet.source} -> {packet.destination}"
            )

        # STEP 5C: IDENTIFY THE TRANSMISSION DIRECTION
        direction = (
            packet.source,
            packet.destination,
        )

        # STEP 5D: CONVERT GENERATION TIME TO NANOSECONDS
        # PacketEvent.generation_time is measured in cycles.
        # Multiply by the clock period to obtain nanoseconds.
        generated = (
            packet.generation_time * clock_period_ns
        )

        # STEP 5E: CALCULATE TRANSMISSION START TIME
        # A packet can only begin transmission when:
        # 1. It has already been generated.
        # 2. The link is available in its direction.
        #
        # max() selects the later of these two times.

        started = max(
            generated,
            next_free[direction],
        )

        # STEP 5F: CALCULATE SERIALIZATION TIME
        # Serialization is the time required to place
        # every byte of the packet onto the link.
        #
        # Formula:
        # serialization_ns = packet_size / bandwidth
        #
        # Bytes / (GB/s) produces ns numerically,
        # assuming decimal gigabytes (10^9 bytes).

        serialization = (
            packet.packet_size / link.bandwidth
        )

        # STEP 5G: CALCULATE TRANSMISSION FINISH TIME
        # Transmission finishes after serialization.

        finished = started + serialization

        # STEP 5H: CALCULATE ARRIVAL TIME
        # After serialization, add the configured
        # physical link latency.
        #
        # total_latency may represent propagation,
        # physical link overhead, and E/O or O/E
        # conversion delays, depending on the link data.
        #
        # Serialization must not already be included
        # in link.total_latency.

        arrived = finished + link.total_latency

        # STEP 5I: UPDATE LINK AVAILABILITY
        # The next packet in the same direction can
        # start when serialization finishes.
        #
        # It does not need to wait for propagation
        # or receiver latency to finish.

        next_free[direction] = finished

        # STEP 5J: CALCULATE QUEUING DELAY
        # Waiting time = actual start - generation time.

        queue_delay = started - generated

        # STEP 5K: CALCULATE END-TO-END LATENCY
        # Total latency includes:
        # - Queue waiting
        # - Serialization
        # - Physical link latency

        latency = arrived - generated

        # STEP 5L: CALCULATE COMMUNICATION ENERGY
        # Convert packet size from bytes to bits.
        packet_bits = packet.packet_size * 8

        # If energy per bit is known, calculate energy.
        # Otherwise, store None to indicate missing data.

        if link.energy_per_bit is not None:
            energy = packet_bits * link.energy_per_bit
        else:
            energy = None

        # STEP 5M: STORE THE PACKET RESULT
        result = PacketResult(
            source=packet.source,
            destination=packet.destination,
            packet_size_bytes=packet.packet_size,
            generation_ns=generated,
            start_ns=started,
            finish_tx_ns=finished,
            arrival_ns=arrived,
            queue_delay_ns=queue_delay,
            serialization_ns=serialization,
            latency_ns=latency,
            energy_pj=energy,
        )

        # Add this packet's result to the output list.
        results.append(result)

    # STEP 6: RETURN ALL PACKET RESULTS
    # The Performance Analyzer will consume this list.
    return results
