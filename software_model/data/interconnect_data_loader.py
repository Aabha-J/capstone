import json

from pathlib import Path
from dataclasses import fields
from typing import get_args, get_type_hints

from software_model.data.enums import InterconnectType
from software_model.data.metrics import Metric, AggregateMetric
from software_model.data.formulas import calculate_bandwidth

from software_model.data.interconnect_classes.interconnect import Interconnect
from software_model.data.interconnect_classes.transmitter import Transmitter
from software_model.data.interconnect_classes.receiver import Receiver
from software_model.data.interconnect_classes.channel import Channel


BANDWIDTH_REL_TOLERANCE = 0.01  # 1%
BANDWIDTH_ABS_TOLERANCE = 0.125  # 1 Gbps, converted to GB/s


# Nested objects belonging to Interconnect.
NESTED_CLASSES = {
    "transmitter": Transmitter,
    "receiver": Receiver,
    "channel": Channel,
}


def load_json(file_path):
    """Read JSON input file."""

    path = Path(file_path)

    if not path.exists():
        raise FileNotFoundError(f"File not found: {path}")

    with path.open("r", encoding="utf-8") as file:
        return json.load(file)


def validate_fields(data, cls, label):
    """Validate JSON keys against dataclass fields."""

    if not isinstance(data, dict):
        raise TypeError(f"{label} must be a JSON object.")

    valid_fields = {
        f.name for f in fields(cls) if f.init
    }

    unknown_fields = set(data) - valid_fields

    if unknown_fields:
        raise ValueError(
            f"Unknown parameters in {label}: {sorted(unknown_fields)}"
        )


def contains_type(annotation, target_type):
    """Check whether a type annotation contains a particular type."""

    if annotation is target_type:
        return True

    return any(
        contains_type(arg, target_type)
        for arg in get_args(annotation)
    )


def create_metric(data):
    """Convert a JSON object into a complete Metric."""

    if data is None:
        return None

    validate_fields(data, Metric, "Metric")

    # A populated Metric must have both a value and a unit.
    if data.get("value") is None:
        raise ValueError("A Metric must have a value.")

    if (
        not isinstance(data["value"], (int, float))
        or isinstance(data["value"], bool)
    ):
        raise TypeError("Metric value must be numeric.")

    if not isinstance(data.get("unit"), str) or not data["unit"].strip():
        raise ValueError("A Metric must have a non-empty unit.")

    if data.get("notes") is not None and not isinstance(data["notes"], str):
        raise TypeError("Metric notes must be a string.")

    return Metric(**data)


def create_aggregate_metric(data):
    """Load a reported aggregate measurement from JSON."""

    if data is None:
        return AggregateMetric()

    validate_fields(data, AggregateMetric, "AggregateMetric")

    # Calculated and partial totals are generated by calculation methods.
    # Only reported measurements can be supplied through JSON.
    unsupported = set(data) - {"reported"}

    if unsupported:
        raise ValueError(
            "JSON aggregate measurements can only contain 'reported'. "
            f"Unsupported fields: {sorted(unsupported)}"
        )

    return AggregateMetric(
        reported=create_metric(data.get("reported"))
    )


def create_components(data, obj):
    """Load component measurements using the initialized component definitions."""

    if data is None:
        return

    if not isinstance(data, dict):
        raise TypeError("Components must be a JSON object.")

    # Component names and supported aggregate measurements come from
    # TRANSMITTER_PARTS or RECEIVER_PARTS through __post_init__().
    unknown_components = set(data) - set(obj.components)

    if unknown_components:
        raise ValueError(
            f"Unknown components: {sorted(unknown_components)}"
        )

    for component, measurements in data.items():

        if not isinstance(measurements, dict):
            raise TypeError(
                f"Measurements for component '{component}' "
                "must be a JSON object."
            )

        valid_metrics = set(obj.components[component])

        unknown_metrics = set(measurements) - valid_metrics

        if unknown_metrics:
            raise ValueError(
                f"Unknown measurements for component '{component}': "
                f"{sorted(unknown_metrics)}"
            )

        for metric_name, measurement in measurements.items():
            obj.components[component][metric_name] = create_metric(
                measurement
            )


def create_dataclass(data, cls, label, interconnect_type=None):
    """Create a dataclass instance and convert its nested measurements."""

    validate_fields(data, cls, label)

    data = data.copy()
    type_hints = get_type_hints(cls)

    kwargs = {}

    # Determine the interconnect type before creating nested TX/RX objects.
    parent_type = interconnect_type

    if "interconnect_type" in data:
        value = data["interconnect_type"]

        try:
            parsed_type = (
                value
                if isinstance(value, InterconnectType)
                else InterconnectType(value.strip().lower())
            )
        except (AttributeError, ValueError):
            raise ValueError(
                f"Invalid interconnect type: {value}"
            )

        if (
            interconnect_type is not None
            and parsed_type != interconnect_type
        ):
            raise ValueError(
                f"{label} interconnect type must match its parent."
            )

        parent_type = parsed_type
        kwargs["interconnect_type"] = parsed_type

    elif interconnect_type is not None:
        kwargs["interconnect_type"] = interconnect_type

    for name, value in data.items():

        if name in ("components", "interconnect_type"):
            continue

        if name in NESTED_CLASSES:
            if value is None:
                kwargs[name] = None
            else:
                nested_cls = NESTED_CLASSES[name]

                kwargs[name] = create_dataclass(
                    value,
                    nested_cls,
                    name,
                    interconnect_type=(
                        parent_type
                        if nested_cls in (Transmitter, Receiver)
                        else None
                    ),
                )

        elif contains_type(type_hints[name], AggregateMetric):
            kwargs[name] = create_aggregate_metric(value)

        elif contains_type(type_hints[name], Metric):
            kwargs[name] = create_metric(value)

        else:
            kwargs[name] = value

    try:
        obj = cls(**kwargs)
    except TypeError as error:
        raise ValueError(
            f"Invalid {label} parameters: {error}"
        ) from error

    # __post_init__ initializes the component dictionary.
    # Populate it afterward with the JSON measurements.
    if "components" in data:
        create_components(data["components"], obj)

    return obj


def calculate_interconnect_aggregates(interconnect):
    """Calculate nested and interconnect aggregates in dependency order."""

    if interconnect.transmitter is not None:
        interconnect.transmitter.calculate_aggregates()

    if interconnect.receiver is not None:
        interconnect.receiver.calculate_aggregates()

    interconnect.calculate_aggregates()


def create_interconnect(data):
    """Convert a JSON dictionary into a fully calculated Interconnect."""

    interconnect = create_dataclass(
        data,
        Interconnect,
        "Interconnect",
    )

    # Validate identification.
    if (
        not isinstance(interconnect.interconnect_id, str)
        or not interconnect.interconnect_id.strip()
    ):
        raise ValueError(
            "Interconnect ID must be a non-empty string."
        )

    if not isinstance(interconnect.interconnect_type, InterconnectType):
        raise ValueError("Invalid interconnect type.")

    # Validate source.
    if (
        not isinstance(interconnect.source, str)
        or not interconnect.source.strip()
    ):
        raise ValueError(
            f"Missing or invalid source for "
            f"{interconnect.interconnect_id}."
        )

    # Calculate all aggregates after loading the nested component data.
    calculate_interconnect_aggregates(interconnect)

    return interconnect


def validate_bandwidth(interconnect):
    """Validate bandwidth and populate the effective bandwidth."""

    reported = interconnect.bandwidth
    reported_value = reported.value if reported else None

    calculated = calculate_bandwidth(interconnect)

    # Compare reported and calculated bandwidth when both exist.
    if reported_value is not None and calculated is not None:

        difference = abs(reported_value - calculated)

        tolerance = max(
            BANDWIDTH_ABS_TOLERANCE,
            BANDWIDTH_REL_TOLERANCE * abs(reported_value),
        )

        if difference > tolerance:
            raise ValueError(
                f"[BANDWIDTH DISCREPANCY] "
                f"{interconnect.interconnect_id}: "
                f"Reported = {reported_value}, "
                f"Calculated = {calculated}, "
                f"Difference = {difference}"
            )

    # Use calculated bandwidth only when no reported value exists.
    if reported_value is None:

        if calculated is None:
            raise ValueError(
                f"Missing bandwidth for {interconnect.interconnect_id}: "
                "insufficient parameters to calculate it."
            )

        interconnect.bandwidth = Metric(
            value=calculated,
            unit="GB/s",
            notes="Calculated from data rate and lane configuration.",
        )

    return {
        "interconnect_id": interconnect.interconnect_id,
        "reported": reported_value,
        "calculated": calculated,
        "effective_bandwidth": interconnect.bandwidth.value,
        "status": (
            "matched"
            if reported_value is not None and calculated is not None
            else "reported_only"
            if reported_value is not None
            else "calculated_only"
        ),
    }


def validate_total_latency(interconnect):
    """Report the calculated or reported total latency aggregate."""

    aggregate = interconnect.total_latency

    return {
        "reported": (
            aggregate.reported.value
            if aggregate.reported else None
        ),
        "calculated": (
            aggregate.calculated_total.value
            if aggregate.calculated_total else None
        ),
        "partial": (
            aggregate.partial_total.value
            if aggregate.partial_total else None
        ),
        "effective": aggregate.value,
        "status": aggregate.status.value,
    }


def load_interconnects(file_path):
    """
    Load JSON data and create Interconnect objects.

    Returns:
        interconnects: List of Interconnect objects
        validation_report: List of bandwidth and latency validation results
    """

    raw_data = load_json(file_path)

    if not isinstance(raw_data, dict):
        raise ValueError("JSON root must be an object.")

    if "interconnects" not in raw_data:
        raise ValueError("Missing 'interconnects' in JSON.")

    entries = raw_data["interconnects"]

    if not isinstance(entries, list):
        raise ValueError("'interconnects' must be a list.")

    interconnects = []
    validation_report = []

    seen_ids = set()

    for entry in entries:

        interconnect = create_interconnect(entry)

        # Check duplicate IDs
        id_key = interconnect.interconnect_id.strip().casefold()

        if id_key in seen_ids:
            raise ValueError(
                f"Duplicate interconnect ID: "
                f"{interconnect.interconnect_id}"
            )

        seen_ids.add(id_key)

        # Validate bandwidth.
        bandwidth_report = validate_bandwidth(interconnect)

        # Report the aggregate calculated during object creation.
        latency_report = validate_total_latency(interconnect)

        interconnects.append(interconnect)

        validation_report.append({
            "interconnect_id": interconnect.interconnect_id,
            "bandwidth": bandwidth_report,
            "total_latency": latency_report,
        })

    return interconnects, validation_report